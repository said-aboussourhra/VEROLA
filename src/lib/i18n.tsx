const DICTS: Record<Lang, typeof en> = { en, fr, ar };
const DIRS: Record<Lang, "ltr" | "rtl"> = { en: "ltr", fr: "ltr", ar: "rtl" };

interface I18nCtx {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (l: Lang) => void;
  t: typeof en;
  L: (o: { en: string; fr: string; ar: string }) => string;
  theme: "light" | "dark";
  toggleTheme: () => void;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [theme, setTheme] = useState<"light" | "dark">("light");

  useEffect(() => {
    const saved = localStorage.getItem("velora-lang") as Lang | null;
    if (saved && DICTS[saved]) setLangState(saved);
    const savedTheme = localStorage.getItem("velora-theme");
    if (savedTheme === "dark" || savedTheme === "light") setTheme(savedTheme);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = DIRS[lang];
  }, [lang]);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const value = useMemo<I18nCtx>(
    () => ({
      lang,
      dir: DIRS[lang],
      setLang: (l) => {
        localStorage.setItem("velora-lang", l);
        setLangState(l);
      },
      t: DICTS[lang],
      L: (o) => o[lang],
      theme,
      toggleTheme: () =>
        setTheme((cur) => {
          const next = cur === "light" ? "dark" : "light";
          localStorage.setItem("velora-theme", next);
          return next;
        }),
    }),
    [lang, theme],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}
